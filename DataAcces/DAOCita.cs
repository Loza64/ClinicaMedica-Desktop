        public bool RerservarCita(Cita date)
        {
            bool responce = false;
            using (con = GetSqlConnection())
            {
                using (scmd = new MySqlCommand())
                {
                    try
                    {
                        con.Open();
                        scmd.Connection = con;
                        scmd.CommandType = CommandType.StoredProcedure;
                        scmd.CommandText = "NewCita";
                        scmd.Parameters.AddWithValue("Usuario",date.id_usuario);
                        scmd.Parameters.AddWithValue("Paciente",date.nombrepaciente);
                        scmd.Parameters.AddWithValue("Parentesco", date.parentesco);
                        scmd.Parameters.AddWithValue("Padecimiento",date.padecimento);
                        scmd.Parameters.AddWithValue("Alergias",date.alergias);
                        scmd.Parameters.AddWithValue("Sintomas",date.enfermedad_sintomas);
                        scmd.Parameters.AddWithValue("Fecha", date.fecha_reservación);
                        scmd.Parameters.AddWithValue("Hora", date.hora);
                        responce = scmd.ExecuteNonQuery() != 0;
                    }
                    catch (MySqlException ex)
                    {
                        throw ex;
                    }
                    catch (SqlNullValueException ex)
                    {
                        throw ex;
                    }
                    catch (TimeoutException ex)
                    {
                        throw ex;
                    }
                    catch (NullReferenceException ex)
                    {
                        throw ex;
                    }
                    catch (ApplicationException ex)
                    {
                        throw ex;
                    }
                    catch (Exception ex)
                    {
                        throw ex;
                    }
                    finally
                    {
                        con.Close();
                        scmd.Parameters.Clear();
                    }
                }
            }
            return responce;

        }
